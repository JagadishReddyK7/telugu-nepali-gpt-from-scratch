"""
Telugu lexicon for the synthetic comparative-reasoning dataset (Model H).

Everything language-specific for Phase 3.1 lives here: entity names, the
attributes that can be compared, and every sentence template. The engine in
``common/reasoning_gen.py`` never sees a Telugu string except through this
dict. Nothing in this file is shared with Model L.

TEMPLATE CONVENTIONS
--------------------
* ``{a}`` / ``{b}`` are entity names, ``{v}`` a rendered number.
* In ``rel_more`` the sentence asserts *a > b*; in ``rel_less`` it asserts
  *a < b*. The engine picks the direction at random so "X is taller than Y" and
  "Y is shorter than X" both occur for the same underlying fact.
* ``ans_more`` / ``ans_less`` are the short relation statements used as gold
  answers for the ``chain_relation`` task. They are single strings, not
  families, so exact match has one canonical target.
* In every list with two or more phrasings, the **last** entry is held out
  from training and appears only in the test split.

ON PHRASING
-----------
People are referred to with the honorific plural (``ఉన్నారు``, ``పెద్దవారు``)
rather than the gendered singular. It reads as ordinary respectful Telugu and
removes the need to track grammatical gender per name. Objects take the neuter
(``ఉంది``). Numbers use ASCII digits, which is how Telugu text on the web and
in print overwhelmingly writes them; the Phase 1 tokenizer encodes them
digit-by-digit.
"""

